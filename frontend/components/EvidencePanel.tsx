import { useState } from "react";
import { motion } from "framer-motion";
import { ChevronDown, ChevronRight, Layers, X } from "lucide-react";
import { EvidenceCard } from "@/components/EvidenceCard";
import type { ChatResponse, ChunkInfo } from "@/types";

type EvidencePanelProps = {
  evidence: ChatResponse | null;
  highlightedIndex?: number | null;
  onClose: () => void;
  onOpenSource?: (chunk: ChunkInfo) => void;
};

const CONFIDENCE_STYLES: Record<
  "High" | "Medium" | "Low",
  { dot: string; text: string; label: string }
> = {
  High:   { dot: "bg-[#4ADE80]", text: "text-[#4ADE80]", label: "High confidence"   },
  Medium: { dot: "bg-accent",    text: "text-accent",     label: "Medium confidence" },
  Low:    { dot: "bg-[#F97316]", text: "text-[#F97316]",  label: "Low confidence"   },
};

export function EvidencePanel({
  evidence,
  highlightedIndex,
  onClose,
  onOpenSource,
}: EvidencePanelProps) {
  const [contextOpen, setContextOpen] = useState(false);

  const chunks     = evidence?.documents ?? [];
  const contextChunks = evidence?.context_documents ?? [];
  const confidence = evidence?.confidence ?? null;
  const conf       = confidence ? CONFIDENCE_STYLES[confidence] : null;

  const citations        = evidence?.citations ?? [];
  const queries          = evidence?.queries ?? [];
  const sourceDistrib    = evidence?.source_distribution ?? {};
  const sourceCount      = Object.keys(sourceDistrib).length;

  return (
    <motion.aside
      initial={{ x: 40, opacity: 0 }}
      animate={{ x: 0, opacity: 1 }}
      exit={{ x: 40, opacity: 0 }}
      transition={{ duration: 0.18, ease: "easeOut" }}
      className="h-full w-[380px] shrink-0 overflow-hidden border-l border-line bg-app/30 backdrop-blur-2xl"
    >
      <div className="flex h-full flex-col">
        {/* ── Header ─────────────────────────────── */}
        <header className="flex shrink-0 items-start justify-between px-7 pb-5 pt-8">
          <div>
            <h2 className="text-[16px] font-semibold leading-6 text-primary">
              Evidence
            </h2>

            <p className="mt-1 text-[12px] font-normal text-secondary">
              {chunks.length
                ? `${chunks.length} supporting excerpt${chunks.length === 1 ? "" : "s"}`
                : "Evidence will appear after an answer"}
            </p>

            {/* Confidence badge */}
            {conf && (
              <span
                className={`mt-2 inline-flex items-center gap-1.5 text-[12px] font-medium ${conf.text}`}
              >
                <span className={`h-1.5 w-1.5 rounded-full ${conf.dot}`} />
                {conf.label}
              </span>
            )}
          </div>

          <button
            type="button"
            aria-label="Close evidence panel"
            onClick={onClose}
            className="rounded-md p-1 text-secondary transition-colors hover:bg-hover hover:text-primary"
          >
            <X size={18} strokeWidth={1.8} />
          </button>
        </header>

        {/* ── Scrollable body ─────────────────────── */}
        <div className="min-h-0 flex-1 overflow-y-auto px-7 pb-6">

          {/* Search queries used for retrieval ─ the standalone question
              (01) plus the alternative phrasings generated by the LLM */}
          {queries.length > 0 && (
            <section className="mb-5">
              <p className="mb-2.5 text-[11px] font-medium uppercase tracking-[0.06em] text-muted">
                Search queries
              </p>
              <ul className="space-y-2">
                {queries.map((q, i) => (
                  <li
                    key={i}
                    className="flex items-start gap-2.5 text-[12.5px] leading-[1.5]"
                  >
                    <span className="mt-0.5 shrink-0 font-mono text-[10px] font-medium tracking-[0.1em] text-accent">
                      {String(i + 1).padStart(2, "0")}
                    </span>
                    <span className={i === 0 ? "text-secondary" : "italic text-muted"}>
                      {q}
                    </span>
                  </li>
                ))}
              </ul>
            </section>
          )}

          {/* Citations */}
          {citations.length > 0 && (
            <section className="mb-5">
              <p className="mb-2.5 text-[11px] font-medium uppercase tracking-[0.06em] text-muted">
                Citations
              </p>
              <ul className="space-y-1.5">
                {citations.map((c, i) => (
                  <li key={i} className="flex items-start gap-2 text-[13px] leading-5 text-secondary">
                    <span className="mt-px shrink-0 text-accent">›</span>
                    {c}
                  </li>
                ))}
              </ul>
            </section>
          )}

          {/* Source distribution — only when multiple files contributed */}
          {sourceCount > 1 && (
            <section className="mb-5">
              <p className="mb-2.5 text-[11px] font-medium uppercase tracking-[0.06em] text-muted">
                Source distribution
              </p>
              <ul className="space-y-3">
                {Object.entries(sourceDistrib)
                  .sort((a, b) => b[1] - a[1])
                  .map(([source, count]) => {
                    const total = Object.values(sourceDistrib).reduce((s, n) => s + n, 0);
                    const pct   = Math.round((count / total) * 100);
                    return (
                      <li key={source} className="space-y-1">
                        <div className="flex items-center justify-between gap-2 text-[12px]">
                          <span className="min-w-0 truncate text-secondary" title={source}>
                            {source}
                          </span>
                          <span className="shrink-0 text-muted">
                            {count} chunk{count !== 1 ? "s" : ""} · {pct}%
                          </span>
                        </div>
                        <div className="h-1 w-full rounded-full bg-elevated">
                          <div
                            className="h-1 rounded-full bg-accent transition-all"
                            style={{ width: `${pct}%` }}
                          />
                        </div>
                      </li>
                    );
                  })}
              </ul>
            </section>
          )}

          {/* ── Cards ──────────────────────────────── */}
          {chunks.length ? (
            <div className="space-y-3">
              {chunks.map((chunk, index) => (
                <EvidenceCard
                  key={`${chunk.source}-${chunk.page ?? "x"}-${index}`}
                  chunk={chunk}
                  index={index}
                  isHighlighted={highlightedIndex === index}
                  onOpenSource={onOpenSource ? () => onOpenSource(chunk) : undefined}
                />
              ))}
            </div>
          ) : (
            <div className="rounded-[10px] border border-line bg-sidebar p-4 text-[13px] leading-5 text-secondary">
              Ask a question after uploading files. Lumen will show only the
              retrieved excerpts returned by your backend.
            </div>
          )}

          {/* ── Additional context ─────────────────── */}
          {contextChunks.length > 0 && (
            <section className="mt-6">
              <button
                type="button"
                onClick={() => setContextOpen((v) => !v)}
                className="flex w-full items-center justify-between gap-2 rounded-md px-1 py-1.5 text-[12px] font-medium text-secondary transition-colors hover:text-primary"
              >
                <span className="inline-flex items-center gap-2">
                  {contextOpen
                    ? <ChevronDown size={13} strokeWidth={2} />
                    : <ChevronRight size={13} strokeWidth={2} />}
                  <Layers size={12} strokeWidth={1.8} className="text-muted" />
                  Additional context the model saw
                </span>
                <span className="text-[11px] text-muted">
                  {contextChunks.length} chunk{contextChunks.length === 1 ? "" : "s"}
                </span>
              </button>

              {contextOpen && (
                <div className="mt-3 space-y-3">
                  {contextChunks.map((chunk, index) => (
                    <EvidenceCard
                      key={`ctx-${chunk.source}-${chunk.page ?? "x"}-${index}`}
                      chunk={chunk}
                      index={index}
                      variant="context"
                      onOpenSource={onOpenSource ? () => onOpenSource(chunk) : undefined}
                    />
                  ))}
                </div>
              )}
            </section>
          )}
        </div>
      </div>
    </motion.aside>
  );
}
